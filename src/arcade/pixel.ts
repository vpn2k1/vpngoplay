const GLYPH_W = 5
const GLYPH_H = 7

/** Width in pixels of `text` at pixel size `px` (glyphs are 5 wide, 1 apart; a space is 3). */
export function pixelTextWidth(text: string, px: number) {
  let cols = 0
  for (const c of text) cols += c === ' ' ? 3 : GLYPH_W + 1
  return Math.max(0, cols - 1) * px
}

/** Pixel-font text with its top edge at y; `align` places x at the left, centre or right. */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  px: number,
  color: string,
  align: 'left' | 'center' | 'right' = 'left',
) {
  const width = pixelTextWidth(text, px)
  let cx = align === 'left' ? x : align === 'center' ? x - width / 2 : x - width
  ctx.fillStyle = color
  for (const c of text.toUpperCase()) {
    const glyph = GLYPHS[c]
    if (glyph)
      for (let r = 0; r < GLYPH_H; r++)
        for (let k = 0; k < GLYPH_W; k++)
          if (glyph[r][k] === '#')
            ctx.fillRect(Math.round(cx + k * px), Math.round(y + r * px), Math.ceil(px), Math.ceil(px))
    cx += (c === ' ' ? 3 : GLYPH_W + 1) * px
  }
}
